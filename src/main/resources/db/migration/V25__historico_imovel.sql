--------------------------------------------------------------------------------
-- US09: histórico de versões do imóvel rural
--------------------------------------------------------------------------------
-- A carga do Airflow (tratada.py) só regrava o imóvel cujo hash_registro mudou
-- (V21). Antes de a linha ser sobrescrita ou apagada, o trigger guarda a versão
-- anterior aqui. Fica no banco, e não na DAG, para valer em qualquer caminho que
-- grave no imovel_rural: a carga, o Revalidar da quarentena ou um ajuste manual.
--
-- dataset_versao_id ........ versão a que a linha guardada pertencia
-- substituida_por_versao_id  versão que a substituiu (no DELETE, a última versão
--                            do mesmo conjunto, que é a carga que a removeu)
-- atributos ................ os campos do imóvel naquela versão, em JSON
--------------------------------------------------------------------------------

CREATE TABLE imovel_rural_historico (
  id                         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  cod_imovel                 VARCHAR2(100 CHAR)  NOT NULL,
  dataset_versao_id          NUMBER              NOT NULL,
  substituida_por_versao_id  NUMBER,
  operacao                   VARCHAR2(10 CHAR)   NOT NULL,
  atributos                  CLOB                NOT NULL,
  geometria                  SDO_GEOMETRY,
  hash_registro              VARCHAR2(40),
  registrado_em              TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_imovel_historico PRIMARY KEY (id),
  CONSTRAINT ck_imovel_historico_op CHECK (operacao IN ('ALTERADO', 'REMOVIDO')),
  CONSTRAINT ck_imovel_historico_json CHECK (atributos IS JSON),
  -- Apagar uma versão (limpeza administrativa ou de teste) leva junto o histórico dela.
  CONSTRAINT fk_imovel_historico_versao FOREIGN KEY (dataset_versao_id)
    REFERENCES dataset_versao (id) ON DELETE CASCADE,
  CONSTRAINT fk_imovel_historico_subst FOREIGN KEY (substituida_por_versao_id)
    REFERENCES dataset_versao (id) ON DELETE SET NULL
);

CREATE INDEX ix_imovel_historico_cod ON imovel_rural_historico (cod_imovel, dataset_versao_id);
CREATE INDEX ix_imovel_historico_subst ON imovel_rural_historico (substituida_por_versao_id);

COMMENT ON TABLE imovel_rural_historico IS 'Versões anteriores de cada imóvel rural, gravadas pelo trigger trg_imovel_rural_historico (US09)';

-- Só guarda quando a carga troca a versão e o conteúdo (hash) mudou: regravar a
-- mesma linha dentro da mesma carga não é uma versão nova.
CREATE OR REPLACE TRIGGER trg_imovel_rural_historico
BEFORE UPDATE OR DELETE ON imovel_rural
FOR EACH ROW
DECLARE
  v_substituta NUMBER;
  v_operacao   VARCHAR2(10);
BEGIN
  IF UPDATING THEN
    IF :NEW.dataset_versao_id = :OLD.dataset_versao_id
       OR (:OLD.hash_registro IS NOT NULL AND :OLD.hash_registro = :NEW.hash_registro) THEN
      RETURN;
    END IF;
    v_operacao := 'ALTERADO';
    v_substituta := :NEW.dataset_versao_id;
  ELSE
    v_operacao := 'REMOVIDO';
    SELECT MAX(d.id) INTO v_substituta
      FROM dataset_versao d
     WHERE d.conjunto = (SELECT conjunto FROM dataset_versao WHERE id = :OLD.dataset_versao_id);
  END IF;

  INSERT INTO imovel_rural_historico
    (cod_imovel, dataset_versao_id, substituida_por_versao_id, operacao, atributos, geometria, hash_registro)
  VALUES
    (:OLD.cod_imovel, :OLD.dataset_versao_id, v_substituta, v_operacao,
     JSON_OBJECT('municipio' VALUE :OLD.municipio,
                 'estado' VALUE :OLD.estado,
                 'area_ha' VALUE :OLD.area_ha,
                 'situacao' VALUE :OLD.situacao,
                 'municipio_id' VALUE :OLD.municipio_id),
     :OLD.geometria, :OLD.hash_registro);
END;
/

-- Versão gravada não muda (DoD da US09). A única mudança aceita é a do ON DELETE SET NULL:
-- substituida_por_versao_id virando nula quando a versão que a substituiu é apagada.
CREATE OR REPLACE TRIGGER trg_imovel_historico_imutavel
BEFORE UPDATE ON imovel_rural_historico
FOR EACH ROW
BEGIN
  IF UPDATING('COD_IMOVEL') OR UPDATING('DATASET_VERSAO_ID') OR UPDATING('OPERACAO')
     OR UPDATING('ATRIBUTOS') OR UPDATING('GEOMETRIA') OR UPDATING('HASH_REGISTRO')
     OR UPDATING('REGISTRADO_EM') OR :NEW.substituida_por_versao_id IS NOT NULL THEN
    RAISE_APPLICATION_ERROR(-20030, 'O histórico do imóvel é imutável: uma versão gravada não pode ser alterada.');
  END IF;
END;
/
