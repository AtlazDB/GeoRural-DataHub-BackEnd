--------------------------------------------------------------------------------
-- Cálculo de indicador cadastrado: uma linha por disparo do "Calcular", com o
-- andamento para a barra de progresso da tela de indicadores.
--------------------------------------------------------------------------------
-- O back cria a linha (NA_FILA) e passa o id para a DAG calcular_indicador; a DAG
-- muda para EM_ANDAMENTO, vai gravando progress/progress_step e termina em
-- CONCLUIDO ou ERRO (com error_message).
--------------------------------------------------------------------------------

CREATE TABLE indicator_calculation (
  id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  indicator_code  VARCHAR2(10 CHAR)  NOT NULL,
  status          VARCHAR2(20 CHAR)  DEFAULT 'NA_FILA' NOT NULL,
  progress        NUMBER(3)          DEFAULT 0 NOT NULL,
  progress_step   VARCHAR2(30 CHAR),
  dag_run_id      VARCHAR2(120 CHAR),
  requested_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  started_at      TIMESTAMP WITH TIME ZONE,
  finished_at     TIMESTAMP WITH TIME ZONE,
  error_message   VARCHAR2(4000 CHAR),
  CONSTRAINT pk_indicator_calculation   PRIMARY KEY (id),
  CONSTRAINT fk_indicator_calc_def      FOREIGN KEY (indicator_code) REFERENCES indicator_definition (code),
  CONSTRAINT ck_indicator_calc_status   CHECK (status IN ('NA_FILA', 'EM_ANDAMENTO', 'CONCLUIDO', 'ERRO')),
  CONSTRAINT ck_indicator_calc_progress CHECK (progress BETWEEN 0 AND 100)
);

-- A tela pede o último cálculo de cada indicador.
CREATE INDEX ix_indicator_calc_code ON indicator_calculation (indicator_code, requested_at);

COMMENT ON TABLE indicator_calculation IS 'Cada disparo do cálculo de um indicador cadastrado, com o progresso para a tela (DAG calcular_indicador)';
COMMENT ON COLUMN indicator_calculation.status IS 'NA_FILA, EM_ANDAMENTO, CONCLUIDO ou ERRO';
COMMENT ON COLUMN indicator_calculation.progress IS '0 a 100, gravado pela DAG';
COMMENT ON COLUMN indicator_calculation.progress_step IS 'Etapa atual: LEITURA, CALCULO ou GRAVACAO';
