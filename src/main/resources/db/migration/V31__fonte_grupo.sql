--------------------------------------------------------------------------------
-- Grupos de fontes: só organizam a tela de Fontes de dados (cards dentro de uma "pasta").
--------------------------------------------------------------------------------
-- Uma fonte grande (ex.: APP do CAR do Paraná) vai em vários pedaços de até 500 MB, cada um numa
-- fonte, porque cada carga no insumo genérico substitui a anterior da mesma fonte. O grupo junta
-- esses pedaços na tela. Não muda nada no processamento nem nos indicadores.
--
-- Apagar o grupo não apaga fontes: elas ficam sem grupo (ON DELETE SET NULL).
--------------------------------------------------------------------------------

CREATE TABLE fonte_grupo (
  id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  nome       VARCHAR2(120 CHAR) NOT NULL,
  criado_em  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_fonte_grupo      PRIMARY KEY (id),
  CONSTRAINT uk_fonte_grupo_nome UNIQUE (nome)
);

ALTER TABLE fonte ADD (
  grupo_id NUMBER,
  CONSTRAINT fk_fonte_grupo FOREIGN KEY (grupo_id) REFERENCES fonte_grupo (id) ON DELETE SET NULL
);

CREATE INDEX ix_fonte_grupo ON fonte (grupo_id);
